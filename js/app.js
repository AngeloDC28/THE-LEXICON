// Floating image preview that appears when hovering an entry-item on desktop.
// A single <div> is reused for all entries to avoid per-item DOM cost.
function initEntryHoverPreview() {
  if (window.innerWidth < 1024) return; // desktop only

  const preview = document.createElement('div');
  preview.id = 'entry-hover-preview';
  preview.setAttribute('aria-hidden', 'true');
  document.body.appendChild(preview);

  const img = document.createElement('img');
  img.decoding = 'async';
  img.loading = 'lazy';
  preview.appendChild(img);

  let currentSrc = '';

  const panel = $('index-panel');
  if (!panel) return;

  panel.addEventListener('mouseenter', (e) => {
    const item = e.target.closest('.entry-item');
    if (!item) return;
    const src = item.dataset.thumb;
    if (!src || src === currentSrc) return;
    currentSrc = src;
    img.src = src;
    preview.classList.add('visible');
  }, true);

  panel.addEventListener('mousemove', (e) => {
    const item = e.target.closest('.entry-item');
    if (!item) {
      preview.classList.remove('visible');
      currentSrc = '';
      return;
    }
    // Position preview to the right of the panel
    const rect = panel.getBoundingClientRect();
    preview.style.top = Math.min(e.clientY - 40, window.innerHeight - 130) + 'px';
    preview.style.left = (rect.right + 8) + 'px';
  }, true);

  panel.addEventListener('mouseleave', () => {
    preview.classList.remove('visible');
    currentSrc = '';
  }, true);
}

function initMobileGestures() {
  if (window.innerWidth >= 1024) return;

  // ── Swipe to navigate images / entries in detail view ────────────────
  const detailView = $('detail-image-view');
  if (detailView) {
    let tx = 0, ty = 0, tracking = false;
    detailView.addEventListener('touchstart', (e) => {
      if (e.touches.length !== 1) return;
      tx = e.touches[0].clientX;
      ty = e.touches[0].clientY;
      tracking = true;
    }, { passive: true });
    detailView.addEventListener('touchend', (e) => {
      if (!tracking || e.changedTouches.length !== 1) return;
      tracking = false;
      const dx = e.changedTouches[0].clientX - tx;
      const dy = e.changedTouches[0].clientY - ty;
      // Only act on predominantly horizontal swipes (> 55px, less vertical drift)
      if (Math.abs(dx) < 55 || Math.abs(dy) > Math.abs(dx) * 0.8) return;
      navigateEntry(dx < 0 ? 1 : -1, archiveData, callbacks);
    }, { passive: true });
  }

  // ── Swipe left on index panel to close the drawer ────────────────────
  const drawer = $('index-panel');
  if (drawer) {
    let sx = 0, sy = 0, dragging = false;
    drawer.addEventListener('touchstart', (e) => {
      if (e.touches.length !== 1) return;
      sx = e.touches[0].clientX;
      sy = e.touches[0].clientY;
      dragging = true;
    }, { passive: true });
    drawer.addEventListener('touchend', (e) => {
      if (!dragging || e.changedTouches.length !== 1) return;
      dragging = false;
      const dx = e.changedTouches[0].clientX - sx;
      const dy = e.changedTouches[0].clientY - sy;
      // Swipe left > 70px and predominantly horizontal → close drawer
      if (dx < -70 && Math.abs(dy) < Math.abs(dx) * 0.6) {
        const isOpen = drawer.classList.contains('translate-x-0');
        if (isOpen) toggleHamburger();
      }
    }, { passive: true });
  }
}
