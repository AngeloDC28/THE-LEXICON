/**
 * Central language-change handler.
 * 1. Restores DOM to English originals.
 * 2. Re-renders JS-controlled strings (getTranslation falls back to English
 *    for any language without a full JSON file, which is intentional).
 * 3. Fires DOM-level translation via Google's unofficial API.
 */
async function applyLanguage(code) {
  // Restore DOM so the translator always works from English source
  domRestore();
  refreshUI();
  // If detail view is open, re-render it so JS-rendered labels (from t())
  // update to the new language — domRestore/domTranslate only covers text
  // nodes the translator touched, not labels rendered directly by the JS.
  if (AppState.selectedEntryId) {
    openDetail(AppState.selectedEntryId, AppState.currentImageIndex, archiveData, callbacks);
  }
  const langEntry  = ALL_LANGS.find(l => l.code === code);
  const langName   = langEntry?.label || code.toUpperCase();
  const googleCode = GOOGLE_LANG[code] || code;
  const toggleBtn  = $('btn-lang-toggle');
  const labelEl    = $('btn-lang-toggle-label');
  if (toggleBtn) toggleBtn.setAttribute('aria-label', `Language: ${langName}. Select language`);
  if (labelEl) labelEl.textContent = code.toUpperCase() + ' ▾';
  document.documentElement.lang = googleCode || code;

  if (code === 'en') {
    showToast('English');
    return;
  }

  // Show a loading indicator so users know translation is in progress
  if (labelEl) labelEl.textContent = '⋯ ▾';
  showToast(langName + ' — translating…');
  try {
    await domTranslate(googleCode);
    if (labelEl) labelEl.textContent = code.toUpperCase() + ' ▾';
    showToast(langName + ' ✓');
  } catch (_) {
    if (labelEl) labelEl.textContent = code.toUpperCase() + ' ▾';
    showToast(langName + ' — partial translation (UI strings only)');
  }
}

function renderLangDropdown() {
  const dd = $('lang-dropdown');
  if (!dd) return;
  dd.innerHTML = ALL_LANGS.map(({ code, label }) => {
    const isActive = code === AppState.language;
    const activeClass = isActive ? 'bg-black text-white dark:bg-acid dark:text-black' : 'hover:bg-black/10 dark:hover:bg-white/10';
    return `<button type="button" role="option" aria-selected="${isActive}" data-lang-code="${code}" lang="${code}" class="w-full text-left px-3 py-2 min-h-[44px] text-[var(--t-mono-xs)] font-mono tracking-widest ${activeClass} transition-colors flex items-center justify-between gap-3 focus-ring">
      <span>${label}</span> <span class="opacity-50 text-[0.5rem] uppercase" aria-hidden="true">${code.toUpperCase()}</span>
    </button>`;
  }).join('');
  dd.querySelectorAll('[data-lang-code]').forEach(btn => {
    btn.addEventListener('click', () => {
      const code = btn.getAttribute('data-lang-code');
      if (!code || code === AppState.language) {
        dd.classList.add('hidden');
        return;
      }
      AppState.language = code;
      try { localStorage.setItem('lexicon-lang', code); } catch(e) {}
      dd.classList.add('hidden');
      $('btn-lang-toggle')?.setAttribute('aria-expanded', 'false');
      applyLanguage(code);
    });
  });
}

function toggleLangDropdown() {
  const dd = $('lang-dropdown');
  const btn = $('btn-lang-toggle');
  if (!dd) return;
  const isHidden = dd.classList.contains('hidden');
  dd.classList.toggle('hidden');
  if (btn) btn.setAttribute('aria-expanded', isHidden ? 'true' : 'false');
  // When opening, move focus to the currently selected option (or first).
  if (isHidden) {
    const selected = dd.querySelector('[aria-selected="true"]') || dd.querySelector('[role="option"]');
    if (selected) requestAnimationFrame(() => selected.focus());
  }
}

// Keyboard navigation for lang dropdown (listbox semantics).
document.addEventListener('keydown', (e) => {
  const dd = document.getElementById('lang-dropdown');
  if (!dd || dd.classList.contains('hidden')) return;
  if (!dd.contains(document.activeElement)) return;
  const options = Array.from(dd.querySelectorAll('[role="option"]'));
  if (!options.length) return;
  const idx = options.indexOf(document.activeElement);
  if (e.key === 'ArrowDown') {
    e.preventDefault();
    options[(idx + 1) % options.length].focus();
  } else if (e.key === 'ArrowUp') {
    e.preventDefault();
    options[(idx - 1 + options.length) % options.length].focus();
  } else if (e.key === 'Home') {
    e.preventDefault();
    options[0].focus();
  } else if (e.key === 'End') {
    e.preventDefault();
    options[options.length - 1].focus();
  } else if (e.key === 'Escape') {
    e.preventDefault();
    dd.classList.add('hidden');
    document.getElementById('btn-lang-toggle')?.setAttribute('aria-expanded', 'false');
    document.getElementById('btn-lang-toggle')?.focus();
  }
});

