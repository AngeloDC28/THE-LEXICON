  set('ws-label-3', 'welcome_step3_label'); set('ws-title-3', 'welcome_step3_title'); set('ws-desc-3', 'welcome_step3_desc');
  const cta = $('btn-welcome-enter'); if (cta) cta.textContent = t('welcome_cta') || cta.textContent;
