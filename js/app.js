let _suppressHashSync = false;

function applyStateFromQuery(params) {
  if (params.has('sort')) AppState.sortMode = params.get('sort');
  if (params.has('q')) {
    AppState.searchQuery = params.get('q');
    const si = $('search-input');
    if (si) si.value = AppState.searchQuery;
  }
  for (const key of Object.keys(AppState.filters)) {
    if (params.has(key)) AppState.filters[key] = params.get(key);
  }
  // Year range from URL (y_min / y_max)
  const yMin = params.has('y_min') ? parseInt(params.get('y_min')) : 1980;
  const yMax = params.has('y_max') ? parseInt(params.get('y_max')) : 2025;
  if (!isNaN(yMin) && !isNaN(yMax)) AppState.yearRange = { min: yMin, max: yMax };

  if (params.has('saved') && params.get('saved') === '1') {
    AppState.bookmarksOnly = true;
    const btn = $('btn-show-bookmarks');
    if (btn) btn.setAttribute('aria-pressed', 'true');
  }
  if (params.has('cat')) AppState.analyticalCat = params.get('cat') || null;
  // Phase 2: view mode (visual | index) is URL-shareable
  if (params.has('mode')) {
    const mode = params.get('mode');
    if (mode === 'index' || mode === 'visual') setViewMode(mode);
  }
}

export function syncHashFromState() {
  if (_suppressHashSync) return;
  // Detail view manages its own URL (/entry/...); don't overwrite it here.
  if (AppState.selectedEntryId) return;
  if (window.location.pathname.startsWith('/entry/')) return;
  const params = new URLSearchParams();
  if (AppState.sortMode && AppState.sortMode !== 'default') params.set('sort', AppState.sortMode);
  if (AppState.searchQuery) params.set('q', AppState.searchQuery);
  for (const [k, v] of Object.entries(AppState.filters)) {
    if (v) params.set(k, v);
  }
  const yr = AppState.yearRange || { min: 1980, max: 2025 };
  if (yr.min > 1980) params.set('y_min', yr.min);
  if (yr.max < 2025) params.set('y_max', yr.max);
  if (AppState.bookmarksOnly) params.set('saved', '1');
  if (AppState.analyticalCat) params.set('cat', AppState.analyticalCat);
  // Phase 2: encode view mode (only if non-default)
  if (AppState.viewMode === 'index') params.set('mode', 'index');
  const view = AppState.currentView || 'grid';
  const qs = params.toString();
  const newHash = '#' + view + (qs ? '?' + qs : '');
  if (window.location.hash === newHash || (view === 'grid' && !qs && !window.location.hash)) return;
  _suppressHashSync = true;
  history.replaceState(null, '', window.location.pathname + window.location.search + newHash);
  setTimeout(() => { _suppressHashSync = false; }, 0);
}

function handleRouting() {
  if (_suppressHashSync) return;

  // /about as a routable URL
  if (window.location.pathname === '/about') {
    document.title = 'About — THE LEXICON';
    const canonical = document.querySelector('link[rel="canonical"]');
    if (canonical) canonical.setAttribute('href', 'https://thelexicon.xyz/about');
    const aboutModal = $('about-modal');
    if (aboutModal && aboutModal.classList.contains('hidden')) {
      const focusEl = aboutModal.querySelector('[data-modal-close]') || aboutModal.querySelector('button');
      aboutModal.classList.remove('hidden');
      if (focusEl) requestAnimationFrame(() => focusEl.focus());
      trapFocus(aboutModal);
    }
    switchView('grid', callbacks);
    return;
  }

  // Path-based entry routes: /entry/{slug}/{imageIndex}
  const entryMatch = window.location.pathname.match(/^\/entry\/([^/]+)(?:\/(\d+))?/);
  if (entryMatch) {
    const id  = entryMatch[1];
    const idx = entryMatch[2] ? parseInt(entryMatch[2]) : 0;
    const entry = archiveData.find(e => e.id === id);
    if (entry) {
      switchView('grid', callbacks);
      openDetail(id, idx, archiveData, callbacks);
    } else if (archiveData.length > 0) {
      // Data is loaded but slug doesn't exist — genuine 404
      switchView('grid', callbacks);
      showToast(getTranslation('entry_not_found', AppState.language) || 'Entry not found — returning to archive');
    }
    // If archiveData is still empty, the safety re-render will handle it
    return;
  }

  // Hash-based routing for grid/filter/view state
  const raw = window.location.hash.slice(1); // strip #
  if (!raw) { switchView('grid', callbacks); return; }

  const [path, query] = raw.split('?');
  const params = new URLSearchParams(query || '');

  // Legacy support: #detail/... hash links still work
  if (path.startsWith('detail/')) {
    const parts = path.replace('detail/', '').split('/');
    const id  = parts[0];
    const idx = parts[1] ? parseInt(parts[1]) : 0;
    openDetail(id, idx, archiveData, callbacks);
    return;
  }

  // Apply persisted filters/sort/search BEFORE switching view
  applyStateFromQuery(params);

  if (path === 'folders')   { switchView('folders', callbacks); return; }
  if (path === 'timeline')  { switchView('timeline', callbacks); return; }
  if (path === 'grid' || path === '') { switchView('grid', callbacks); return; }

  // Fallback: maybe it's a bare entry id in the hash
  const entry = archiveData.find(e => e.id === path);
  if (entry) {
    openDetail(path, 0, archiveData, callbacks);
  } else {
    switchView('grid', callbacks);
  }
}

